const STORAGE_KEY = 'bachpan_gallery_memories_v2'

// Load items from localStorage or fallback
export function getStoredMemories() {
  if (typeof window === 'undefined') return INITIAL_GALLERY_MEMORIES
  try {
    const raw = localStorage.getItem(STORAGE_KEY)
    if (raw) {
      const parsed = JSON.parse(raw)
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed
      }
    }
  } catch (e) {
    console.warn('Error reading from localStorage:', e)
  }
  return INITIAL_GALLERY_MEMORIES
}

// Save items to localStorage
export function saveMemories(memories) {
  if (typeof window === 'undefined') return
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(memories))
    window.dispatchEvent(new Event('bachpan-gallery-updated'))
  } catch (e) {
    console.error('Error writing to localStorage:', e)
  }
}

// Add a new memory item
export function addMemoryItem(newItem) {
  const current = getStoredMemories()
  const formatted = {
    ...newItem,
    id: newItem.id || `mem-${Date.now()}`,
    date: newItem.date || new Date().toISOString().split('T')[0],
  }
  const updated = [formatted, ...current]
  // Sort descending by date
  updated.sort((a, b) => new Date(b.date) - new Date(a.date))
  saveMemories(updated)

  // Asynchronously attempt to save to Supabase if configured
  import('./supabase').then(({ getSupabase, isSupabaseConfigured }) => {
    if (isSupabaseConfigured()) {
      const supabase = getSupabase()
      if (supabase) {
        supabase
          .from('gallery_items')
          .insert([
            {
              title: formatted.title,
              description: formatted.caption || '',
              media_type: formatted.media_type,
              url: formatted.url,
              category: formatted.category,
            },
          ])
          .then(({ error }) => {
            if (error) console.warn('Supabase gallery insert notice:', error.message)
          })
          .catch((err) => console.warn('Supabase gallery network notice:', err))
      }
    }
  }).catch(() => {})

  return updated
}

// Update an existing memory item
export function updateMemoryItem(id, updatedFields) {
  const current = getStoredMemories()
  const updated = current.map((item) => {
    if (item.id === id) {
      return { ...item, ...updatedFields }
    }
    return item
  })
  updated.sort((a, b) => new Date(b.date) - new Date(a.date))
  saveMemories(updated)
  return updated
}

// Delete a memory item (locally and on Supabase if configured)
export function deleteMemoryItem(id) {
  const current = getStoredMemories()
  const toDelete = current.find((item) => item.id === id)
  const updated = current.filter((item) => item.id !== id)
  saveMemories(updated)

  if (toDelete) {
    import('./supabase').then(({ getSupabase, isSupabaseConfigured }) => {
      if (isSupabaseConfigured()) {
        const supabase = getSupabase()
        if (supabase) {
          supabase
            .from('gallery_items')
            .delete()
            .or(`id.eq.${id},title.eq.${toDelete.title}`)
            .then(({ error }) => {
              if (error) console.warn('Supabase delete notice:', error.message)
            })
            .catch(() => {})
        }
      }
    }).catch(() => {})
  }

  return updated
}

// Delete multiple memory items in batch
export function deleteBatchMemories(ids) {
  const idSet = new Set(ids)
  const current = getStoredMemories()
  const updated = current.filter((item) => !idSet.has(item.id))
  saveMemories(updated)

  import('./supabase').then(({ getSupabase, isSupabaseConfigured }) => {
    if (isSupabaseConfigured()) {
      const supabase = getSupabase()
      if (supabase) {
        supabase
          .from('gallery_items')
          .delete()
          .in('id', ids)
          .catch(() => {})
      }
    }
  }).catch(() => {})

  return updated
}

// Clear all moments
export function clearAllMemories() {
  saveMemories([])
  return []
}

// Reset memories to initial demo state
export function resetToDemoMemories() {
  saveMemories(INITIAL_GALLERY_MEMORIES)
  return INITIAL_GALLERY_MEMORIES
}

// Helper to group items by Month & Year
export function groupMemoriesByMonth(memories) {
  const groups = {}

  // Sort memories descending by date
  const sorted = [...memories].sort((a, b) => new Date(b.date) - new Date(a.date))

  sorted.forEach((item) => {
    const d = new Date(item.date)
    const year = d.getFullYear()
    const monthIndex = d.getMonth()
    const monthKey = `${year}-${String(monthIndex + 1).padStart(2, '0')}`

    const monthLabel = d.toLocaleString('en-US', { month: 'long', year: 'numeric' })

    if (!groups[monthKey]) {
      groups[monthKey] = {
        monthKey,
        monthLabel,
        year,
        monthIndex,
        items: [],
      }
    }
    groups[monthKey].items.push(item)
  })

  // Return array sorted by monthKey descending
  return Object.values(groups).sort((a, b) => b.monthKey.localeCompare(a.monthKey))
}

// Helper to format a single date nicely (e.g. "24 Oct 2026", "Saturday")
export function formatDateDetails(dateString) {
  try {
    const d = new Date(dateString)
    const dayNumber = d.getDate()
    const monthShort = d.toLocaleString('en-US', { month: 'short' }).toUpperCase()
    const weekday = d.toLocaleString('en-US', { weekday: 'long' })
    const fullDate = d.toLocaleString('en-US', { day: 'numeric', month: 'long', year: 'numeric' })
    return { dayNumber, monthShort, weekday, fullDate }
  } catch (_) {
    return { dayNumber: '—', monthShort: '', weekday: '', fullDate: dateString }
  }
}
